import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { GraduationCap, Sparkles } from "lucide-react";
import { useEffect, useState } from "react";
import { formatDate, Pill, RowMenu, Tabs } from "@/components/admin/shell";
import { PageHead } from "@/components/facilitator/shell";
import { PublishToGroupsDialog } from "@/components/facilitator/group-course-actions";
import { publishBlocker, useUnpublishFromGroups } from "@/lib/facilitator/group-course-publish";
import { ConfirmDialog } from "@/components/facilitator/ui";
import { Button } from "@/components/ui/button";
import { DropdownMenuItem, DropdownMenuSeparator } from "@/components/ui/dropdown-menu";
import { useAuth } from "@/hooks/use-auth";
import { adminErrorMessage } from "@/lib/admin/api";
import { cropLabel, cropsQueryOptions } from "@/lib/admin/backend-groups";
import {
  difficultyLabels,
  generationStatusLabels,
  generationStatusTone,
  type AdminCourse,
} from "@/lib/admin/backend-courses";
import {
  facilitatorCourseListQueryOptions,
  groupCourseStatusLabels,
} from "@/lib/facilitator/backend-courses";

type View = "group" | "platform";

export const Route = createFileRoute("/_authenticated/facilitator/courses/")({
  validateSearch: (search: Record<string, unknown>): { view?: View } =>
    search["view"] === "platform" || search["view"] === "group" ? { view: search["view"] } : {},
  component: Courses,
});

/**
 * Facilitator courses from the backend. "My group courses" are generated by AI from a
 * structure the facilitator designs and are shared with one of their groups only.
 */
function Courses() {
  const search = Route.useSearch();
  const navigate = useNavigate({ from: "/facilitator/courses/" });
  const { permissions, loading } = useAuth();
  const canRead = permissions.includes("courses:read");
  const canGenerate = permissions.includes("course-generations:create");
  const view: View = search.view ?? "group";
  const [query, setQuery] = useState("");
  const [debounced, setDebounced] = useState("");
  const [cropId, setCropId] = useState("all");
  const [page, setPage] = useState(1);
  const [publishing, setPublishing] = useState<AdminCourse | null>(null);
  const [withdrawing, setWithdrawing] = useState<AdminCourse | null>(null);
  const unpublish = useUnpublishFromGroups();

  useEffect(() => {
    const timer = setTimeout(() => setDebounced(query.trim()), 300);
    return () => clearTimeout(timer);
  }, [query]);
  useEffect(() => setPage(1), [view]);

  const enabled = canRead && !loading;
  const crops = useQuery(cropsQueryOptions(enabled));
  const list = useQuery(
    facilitatorCourseListQueryOptions(
      {
        ownership: view === "group" ? "GROUP" : "PLATFORM",
        page,
        ...(debounced ? { search: debounced } : {}),
        ...(cropId !== "all" ? { cropId } : {}),
      },
      enabled,
    ),
  );

  const head = (
    <PageHead
      title="Courses"
      text="Courses you generate with AI and publish to your groups, and published platform courses you can teach."
    >
      <Button asChild variant="outline">
        <Link to="/courses">
          <GraduationCap aria-hidden />
          Learn: open Amasomo
        </Link>
      </Button>
      {canGenerate && (
        <Button asChild>
          <Link to="/facilitator/courses/generate">
            <Sparkles aria-hidden />
            Create course
          </Link>
        </Button>
      )}
    </PageHead>
  );
  if (loading)
    return (
      <>
        {head}
        <p className="fac-empty">Loading courses…</p>
      </>
    );
  if (!canRead)
    return (
      <>
        {head}
        <p className="fac-empty">You do not have permission to view courses.</p>
      </>
    );

  const rows = list.data?.data ?? [];
  const meta = list.data?.meta;
  const totalPages = Math.max(1, meta?.totalPages ?? 1);

  return (
    <>
      {head}
      <Tabs
        value={view}
        onChange={(value) => void navigate({ search: { view: value } })}
        options={[
          { value: "group", label: "My group courses" },
          { value: "platform", label: "Courses to teach" },
        ]}
      />
      <div className="admin-filters">
        <input
          aria-label="Search courses"
          placeholder="Search courses"
          value={query}
          onChange={(event) => {
            setQuery(event.target.value);
            setPage(1);
          }}
        />
        <select
          aria-label="Crop"
          value={cropId}
          onChange={(event) => {
            setCropId(event.target.value);
            setPage(1);
          }}
        >
          <option value="all">All crops</option>
          {(crops.data ?? []).map((crop) => (
            <option key={crop.id} value={crop.id}>
              {cropLabel(crop)}
            </option>
          ))}
        </select>
      </div>
      {list.isError ? (
        <div className="fac-empty" role="alert">
          <p>{adminErrorMessage(list.error, "Courses could not be loaded from the server.")}</p>
          <Button className="mt-3" variant="outline" onClick={() => void list.refetch()}>
            Try again
          </Button>
        </div>
      ) : list.isLoading ? (
        <p className="fac-empty">Loading courses…</p>
      ) : rows.length === 0 ? (
        <div className="fac-empty">
          {view === "group" ? (
            <>
              <p>You have not generated a course yet.</p>
              {canGenerate && (
                <Button asChild className="mt-3">
                  <Link to="/facilitator/courses/generate">
                    <Sparkles aria-hidden />
                    Create course
                  </Link>
                </Button>
              )}
            </>
          ) : (
            <p>No published platform course matches these filters.</p>
          )}
        </div>
      ) : (
        <>
          <div className="staff-table" aria-busy={list.isFetching}>
            <table className="w-full text-sm">
              <thead>
                <tr>
                  <th>Course</th>
                  {view === "group" && <th>Published to</th>}
                  <th>Crop</th>
                  <th>Level</th>
                  <th>Status</th>
                  <th>{view === "group" ? "Updated" : "Published"}</th>
                  <th className="col-actions">Actions</th>
                </tr>
              </thead>
              <tbody>
                {rows.map((course) => {
                  const blocker = publishBlocker(course);
                  return (
                    <tr key={course.id}>
                      <td>
                        <Link
                          className="font-bold"
                          to="/facilitator/courses/$courseId"
                          params={{ courseId: course.id }}
                        >
                          {course.title}
                        </Link>
                        <small className="block text-muted-foreground">
                          {course.shortDescription}
                        </small>
                      </td>
                      {view === "group" && (
                        <td>
                          {course.sharedWithGroups.length
                            ? course.sharedWithGroups.map((group) => group.name).join(", ")
                            : "Not published yet"}
                        </td>
                      )}
                      <td>{cropLabel(course.crop)}</td>
                      <td>{difficultyLabels[course.difficulty]}</td>
                      <td>
                        {view === "group" ? (
                          <Pill
                            tone={
                              course.status === "PUBLISHED"
                                ? "ok"
                                : course.status === "ARCHIVED"
                                  ? "muted"
                                  : "info"
                            }
                          >
                            {groupCourseStatusLabels[course.status]}
                          </Pill>
                        ) : (
                          <Pill tone="ok">Published</Pill>
                        )}
                        {course.generation && course.generation.status !== "COMPLETED" && (
                          <span className="mt-1 block">
                            <Pill tone={generationStatusTone(course.generation.status)}>
                              {generationStatusLabels[course.generation.status]}
                            </Pill>
                          </span>
                        )}
                      </td>
                      <td>
                        {formatDate(view === "group" ? course.updatedAt : course.publishedAt)}
                      </td>
                      <td className="col-actions">
                        <RowMenu label={course.title}>
                          <DropdownMenuItem asChild>
                            <Link
                              to="/facilitator/courses/$courseId"
                              params={{ courseId: course.id }}
                            >
                              Open
                            </Link>
                          </DropdownMenuItem>
                          {course.facilitatorOwner && !blocker && (
                            <>
                              <DropdownMenuSeparator />
                              <DropdownMenuItem onSelect={() => setPublishing(course)}>
                                {course.status === "PUBLISHED"
                                  ? "Change groups"
                                  : "Publish to groups"}
                              </DropdownMenuItem>
                            </>
                          )}
                          {course.facilitatorOwner && course.status === "PUBLISHED" && (
                            <DropdownMenuItem onSelect={() => setWithdrawing(course)}>
                              Stop publishing
                            </DropdownMenuItem>
                          )}
                        </RowMenu>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          {totalPages > 1 && (
            <div className="admin-actions mt-3 items-center">
              <Button
                size="sm"
                variant="outline"
                disabled={page <= 1}
                onClick={() => setPage(page - 1)}
              >
                Previous
              </Button>
              <span className="text-sm">
                Page {page} of {totalPages} · {meta?.total ?? 0} course(s)
              </span>
              <Button
                size="sm"
                variant="outline"
                disabled={page >= totalPages}
                onClick={() => setPage(page + 1)}
              >
                Next
              </Button>
            </div>
          )}
        </>
      )}
      <PublishToGroupsDialog course={publishing} onClose={() => setPublishing(null)} />
      <ConfirmDialog
        open={!!withdrawing}
        onOpenChange={(open) => {
          if (!open) setWithdrawing(null);
        }}
        title="Stop publishing this course?"
        text={
          withdrawing
            ? `${withdrawing.title}: farmers in ${withdrawing.sharedWithGroups.map((group) => group.name).join(", ") || "your groups"} stop seeing it. Their progress is kept and you can publish it again.`
            : ""
        }
        confirmLabel="Stop publishing"
        onConfirm={() => {
          if (withdrawing) unpublish.mutate(withdrawing);
          setWithdrawing(null);
        }}
      />
    </>
  );
}
