type Tab = "new" | "requests";

export const Route = createFileRoute("/_authenticated/admin/courses/generate")({
  validateSearch: (search: Record<string, unknown>): { tab?: Tab } =>
    search["tab"] === "requests" || search["tab"] === "new" ? { tab: search["tab"] } : {},
  component: GeneratePage,
});

/**
 * Courses are generated by AI only. The administrator designs the structure (chapters and
 * sub-chapters), chooses the learning formats and the Knowledge Base sources, and the
 * course-generation model writes the content (POST /course-generations).
 */
function GeneratePage() {
  const search = Route.useSearch();
  const navigate = useNavigate({ from: "/admin/courses/generate" });
  const { permissions, loading } = useAuth();
  const canCreate = permissions.includes("course-generations:create");
  const canRead = permissions.includes("course-generations:read");
  const tab: Tab = search.tab ?? (canCreate ? "new" : "requests");

  return (
    <>
      <Link
        to="/admin/courses"
        className="inline-flex items-center gap-1 text-sm font-bold text-primary"
      >
        <ArrowLeft className="size-4" aria-hidden />
        Back to courses
      </Link>
      <PageHead
        title="Generate a course with AI"
        text="Design the course structure, choose how farmers learn and which Knowledge Base documents to use. The AI model writes every sub-chapter; you review the course before publishing."
      />
      {loading ? (
        <p className="fac-empty">Loading…</p>
      ) : !canCreate && !canRead ? (
        <p className="fac-empty">You do not have permission to generate courses.</p>
      ) : (
        <>
          <Tabs
            value={tab}
            onChange={(value) => void navigate({ search: { tab: value } })}
            options={[
              ...(canCreate ? [{ value: "new" as const, label: "New course" }] : []),
              ...(canRead ? [{ value: "requests" as const, label: "Generation requests" }] : []),
            ]}
          />
          {tab === "new" && canCreate && (
            <CourseGenerationForm
              onCreated={(generation) =>
                void navigate({
                  to: "/admin/courses/$courseId",
                  params: { courseId: generation.course.id },
                })
              }
            />
          )}
          {tab === "requests" && canRead && <Requests />}
        </>
      )}
    </>
  );
}

function Requests() {
  const queryClient = useQueryClient();
  const [status, setStatus] = useState<GenerationStatus | "all">("all");
  const [page, setPage] = useState(1);
  const list = useQuery({
    ...courseGenerationsQueryOptions({ page, ...(status !== "all" ? { status } : {}) }, true),
    placeholderData: keepPreviousData,
  });
  const cancel = useMutation({
    mutationFn: (id: string) =>
      adminApi<CourseGeneration>("POST", `course-generations/${id}/cancel`, { body: {} }),
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: adminGenerationsKey });
      void queryClient.invalidateQueries({ queryKey: adminCoursesKey });
      toast.success("Generation request cancelled. The draft course is kept.");
    },
    onError: (error) =>
      toast.error(adminErrorMessage(error, "The request could not be cancelled.")),
  });
  const rows = list.data?.data ?? [];
  const meta = list.data?.meta;
  const totalPages = Math.max(1, meta?.totalPages ?? 1);
  return (
    <section>
      <div className="admin-filters">
        <select
          aria-label="Status"
          value={status}
          onChange={(event) => {
            setStatus(event.target.value as GenerationStatus | "all");
            setPage(1);
          }}
        >
          <option value="all">All statuses</option>
          {(Object.keys(generationStatusLabels) as GenerationStatus[]).map((item) => (
            <option key={item} value={item}>
              {generationStatusLabels[item]}
            </option>
          ))}
        </select>
      </div>
      {list.isError ? (
        <p className="fac-empty" role="alert">
          {adminErrorMessage(list.error, "Requests could not be loaded.")}
        </p>
      ) : list.isLoading ? (
        <p className="fac-empty">Loading requests…</p>
      ) : rows.length === 0 ? (
        <p className="fac-empty">No generation requests yet.</p>
      ) : (
        <>
          <div className="staff-table" aria-busy={list.isFetching}>
            <table className="w-full text-sm">
              <thead>
                <tr>
                  <th>Course</th>
                  <th>For</th>
                  <th>Structure</th>
                  <th>Formats</th>
                  <th>Sources</th>
                  <th>Requested</th>
                  <th>Status</th>
                  <th className="col-actions">Actions</th>
                </tr>
              </thead>
              <tbody>
                {rows.map((row) => (
                  <tr key={row.id}>
                    <td>
                      <Link
                        className="font-bold"
                        to="/admin/courses/$courseId"
                        params={{ courseId: row.course.id }}
                      >
                        {row.course.title}
                      </Link>
                    </td>
                    <td>
                      {row.facilitatorGroup ? `Group: ${row.facilitatorGroup.name}` : "Platform"}
                    </td>
                    <td>
                      {row.chapters.length} chapter(s) ·{" "}
                      {row.chapters.reduce((sum, chapter) => sum + chapter.subChapters.length, 0)}{" "}
                      sub-chapter(s)
                    </td>
                    <td>{row.contentFormats.map((format) => format.toLowerCase()).join(", ")}</td>
                    <td>{row.knowledgeSources.length}</td>
                    <td>
                      {formatDateTime(row.createdAt)}
                      <small className="block text-muted-foreground">
                        {row.requestedBy.fullName}
                      </small>
                    </td>
                    <td>
                      <Pill tone={generationStatusTone(row.status)}>
                        {generationStatusLabels[row.status]}
                      </Pill>
                      {row.statusMessage && (
                        <small className="block max-w-xs text-muted-foreground">
                          {row.statusMessage}
                        </small>
                      )}
                    </td>
                    <td className="col-actions">
                      {row.status === "PENDING" && (
                        <ConfirmButton
                          label="Cancel"
                          title="Cancel this generation request?"
                          text="The AI will not write this course. The draft course and its structure are kept."
                          onConfirm={() => cancel.mutate(row.id)}
                        />
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {totalPages > 1 && (
            <div className="admin-actions mt-3 items-center">
              <Button
                size="sm"
                variant="outline"
                disabled={page <= 1}
                onClick={() => setPage(page - 1)}
              >
                Previous
              </Button>
              <span className="text-sm">
                Page {page} of {totalPages} · {meta?.total ?? 0} request(s)
              </span>
              <Button
                size="sm"
                variant="outline"
                disabled={page >= totalPages}
                onClick={() => setPage(page + 1)}
              >
                Next
              </Button>
            </div>
          )}
        </>
      )}
    </section>
  );
}
